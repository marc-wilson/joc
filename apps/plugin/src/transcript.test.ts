import assert from 'node:assert/strict';
import { test } from 'node:test';
import { parseLines } from './transcript.ts';

// Slash commands as Claude Code records them. Made-up fixtures in the transcript's own shapes.

const at = '2026-10-18T10:00:00.000Z';
const user = (uuid: string, content: string, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ type: 'user', uuid, timestamp: at, message: { content }, ...extra });
const system = (uuid: string, content: string, extra: Record<string, unknown> = {}) =>
  JSON.stringify({
    type: 'system',
    subtype: 'local_command',
    uuid,
    timestamp: at,
    content,
    level: 'info',
    isMeta: false,
    ...extra,
  });

test('a built-in command and what it printed become a command and its output', () => {
  const { items } = parseLines(
    [
      user(
        'c0',
        '<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>',
        {
          isMeta: true,
        },
      ),
      user(
        'c1',
        '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>sonnet</command-args>',
      ),
      user('c2', '<local-command-stdout>Set model to Sonnet</local-command-stdout>', {
        parentUuid: 'c1',
      }),
    ],
    '/work',
  );
  assert.deepEqual(items, [
    { id: 'c1', at, kind: 'command', name: 'model', args: 'sonnet' },
    {
      id: 'c2',
      at,
      kind: 'command_output',
      commandId: 'c1',
      text: 'Set model to Sonnet',
      isError: false,
    },
  ]);
});

test('a skill or plugin command is a command, with its tags in either order', () => {
  const { items } = parseLines(
    [
      user(
        's1',
        '<command-message>harbor:deploy</command-message>\n<command-name>/harbor:deploy</command-name>\n<command-args>staging</command-args>',
        { origin: { kind: 'human' } },
      ),
      // The skill's own text, for Claude only.
      user('s2', 'Deploy harbor-labs/atlas-web to the named environment.', { isMeta: true }),
      user('s3', '<command-message>review</command-message>\n<command-name>/review</command-name>'),
    ],
    '/work',
  );
  assert.deepEqual(items, [
    { id: 's1', at, kind: 'command', name: 'harbor:deploy', args: 'staging' },
    { id: 's3', at, kind: 'command', name: 'review', args: '' },
  ]);
});

test('commands and output recorded as system entries are read too', () => {
  const { items } = parseLines(
    [
      system(
        'l1',
        '<command-name>/cost</command-name>\n<command-message>cost</command-message>\n<command-args></command-args>',
      ),
      system(
        'l2',
        `<local-command-stdout>${String.fromCharCode(27)}[1mTotal cost:${String.fromCharCode(27)}[22m $0.42</local-command-stdout>`,
        { parentUuid: 'l1', commandRun: { command: 'cost', args: '' } },
      ),
      system('l3', '<local-command-stderr>Unknown model: atlas-1</local-command-stderr>', {
        parentUuid: 'l1',
      }),
      // Printed nothing.
      system('l4', '<local-command-stdout></local-command-stdout>', { parentUuid: 'l1' }),
      // Other system entries aren't conversation.
      JSON.stringify({ type: 'system', subtype: 'turn_duration', uuid: 'l5', timestamp: at }),
    ],
    '/work',
  );
  assert.deepEqual(items, [
    { id: 'l1', at, kind: 'command', name: 'cost', args: '' },
    {
      id: 'l2',
      at,
      kind: 'command_output',
      commandId: 'l1',
      text: 'Total cost: $0.42',
      isError: false,
    },
    {
      id: 'l3',
      at,
      kind: 'command_output',
      commandId: 'l1',
      text: 'Unknown model: atlas-1',
      isError: true,
    },
  ]);
});

test('an assistant message with plain string content is not mistaken for a prompt', () => {
  const line = JSON.stringify({
    type: 'assistant',
    uuid: 'a1',
    timestamp: at,
    message: { content: 'hi' },
  });
  assert.deepEqual(parseLines([line], '/work').items, []);
});
